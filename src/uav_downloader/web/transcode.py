"""On-demand transcoding of library videos to HLS for browser playback.

Files the browser cannot decode natively (see probe.py) are transcoded
by ffmpeg into HLS segments under ``<state>/transcode/<id>`` and served
by server.py.  The playlist is generated by the server from the probed
duration — a full-length VOD playlist with absolute segment indexes —
so the player's progress bar always reflects the real timeline.  ffmpeg
runs write segments on demand: each run starts at a segment index with
input seeking plus ``-copyts`` and forced keyframes on the absolute 4s
grid, so segments produced by different runs line up and stay valid.
A segment request that lands far ahead of (or behind) the current run
restarts ffmpeg at the requested index; completed segments are never
re-encoded.

Hardware encoding via VAAPI is attempted when a render node exists; if
that ffmpeg dies without producing the wanted segment, VAAPI is marked
broken for the process lifetime and the run respawns with libx264.
Every run's stderr lands in the session dir (``ffmpeg.log`` /
``ffmpeg-vaapi.log``) and is preserved under ``<state>/transcode-logs``
when the session is removed, so a VAAPI failure can be diagnosed after
the fact.
"""
from __future__ import annotations

import math
import os
from pathlib import Path
import re
import secrets
import shutil
import signal
import subprocess
import threading
import time

from . import library, metadata, probe

SEG_LEN = 4.0             # Seconds per HLS segment; the absolute grid.
MAX_SESSIONS = 2
_IDLE_LIMIT = 90          # Seconds without a playlist/segment hit.
_REAPER_INTERVAL = 5
_SEG_WAIT = 25            # Seconds a segment request waits for ffmpeg.
_FRONTIER_WAIT = 8        # Segments ahead of the frontier worth waiting for.
_VAAPI_DEVICE = '/dev/dri/renderD128'
_ID_RE = re.compile(r'^[a-f0-9]{16}$')
_SEG_RE = re.compile(r'^seg(\d{5})\.ts$')
_LOG_KEEP = 10

_lock = threading.Lock()
_sessions = {}
_vaapi_broken = False
_last_vaapi_error = None
_reaper_started = False


def transcode_root():
    path = Path(metadata.state_dir()) / 'transcode'
    path.mkdir(parents=True, exist_ok=True)
    return path


def valid_id(session_id):
    return isinstance(session_id, str) and bool(_ID_RE.match(session_id))


def _seg_name(index):
    return f'seg{index:05d}.ts'


def segment_count(duration):
    return max(1, math.ceil(duration / SEG_LEN - 1e-9))


def build_playlist(session):
    """The full-length VOD playlist for *session*, generated on the fly."""
    duration = session['duration']
    count = session['nsegments']
    lines = ['#EXTM3U', '#EXT-X-VERSION:3', '#EXT-X-PLAYLIST-TYPE:VOD',
             '#EXT-X-TARGETDURATION:6', '#EXT-X-MEDIA-SEQUENCE:0']
    for i in range(count):
        seg = SEG_LEN if i < count - 1 else duration - SEG_LEN * (count - 1)
        lines.append(f'#EXTINF:{max(seg, 0.001):.3f},')
        lines.append(_seg_name(i))
    lines.append('#EXT-X-ENDLIST')
    return '\n'.join(lines) + '\n'


def _video_filter(encoder):
    if encoder == 'vaapi':
        return "scale_vaapi=w=-2:h='min(1080,ih)'"
    return "scale=w=-2:h='min(1080,ih)'"


def _build_command(session, start_index):
    cmd = ['ffmpeg', '-hide_banner', '-loglevel', 'error', '-nostdin']
    start = start_index * SEG_LEN
    if start > 0:
        cmd += ['-ss', f'{start:.3f}']
    if session['run_encoder'] == 'vaapi':
        cmd += ['-hwaccel', 'vaapi', '-hwaccel_device', _VAAPI_DEVICE,
                '-hwaccel_output_format', 'vaapi']
    # -copyts keeps output timestamps on the source's absolute timeline,
    # so a run started at segment N emits timestamps starting at N*SEG_LEN
    # and its segments align with the server-generated playlist.
    cmd += ['-copyts', '-i', str(session['target']),
            '-map', '0:v:0', '-map', '0:a:0?',
            '-vf', _video_filter(session['run_encoder'])]
    if session['run_encoder'] == 'vaapi':
        cmd += ['-c:v', 'h264_vaapi', '-b:v', '8M']
    else:
        cmd += ['-c:v', 'libx264', '-preset', 'veryfast', '-crf', '23']
    cmd += ['-force_key_frames', f'expr:gte(t,n_forced*{SEG_LEN:g})',
            '-c:a', 'aac', '-b:a', '192k', '-ac', '2',
            '-f', 'hls', '-hls_time', str(int(SEG_LEN)),
            '-hls_list_size', '0', '-start_number', str(start_index),
            '-hls_flags', 'temp_file',
            '-hls_segment_filename', str(session['dir'] / 'seg%05d.ts'),
            str(session['dir'] / 'scratch.m3u8')]
    return cmd


def _completed_indexes(session):
    try:
        names = os.listdir(session['dir'])
    except OSError:
        return []
    found = []
    for name in names:
        match = _SEG_RE.match(name)
        if match:
            found.append(int(match.group(1)))
    return found


def _frontier(session):
    """Highest completed segment index, or -1 when none exists yet."""
    done = _completed_indexes(session)
    return max(done) if done else -1


def _kill(session):
    proc = session.get('proc')
    if proc is None:
        return
    if proc.poll() is None:
        try:
            os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
        except (OSError, ProcessLookupError):
            try:
                proc.kill()
            except OSError:
                pass
    try:
        proc.wait(timeout=5)
    except Exception:
        pass


def _start_run(session, start_index):
    """(Re)start the session's ffmpeg at *start_index*.  Caller holds _lock."""
    _kill(session)
    encoder = ('vaapi' if Path(_VAAPI_DEVICE).exists() and not _vaapi_broken
               else 'libx264')
    session['encoder'] = encoder
    session['run_encoder'] = encoder
    session['run_start_index'] = start_index
    for tmp in session['dir'].glob('*.tmp'):
        try:
            tmp.unlink()
        except OSError:
            pass
    log_name = 'ffmpeg-vaapi.log' if encoder == 'vaapi' else 'ffmpeg.log'
    log = open(session['dir'] / log_name, 'wb')
    try:
        proc = subprocess.Popen(
            _build_command(session, start_index),
            stdout=subprocess.DEVNULL, stderr=log,
            start_new_session=True)
    finally:
        log.close()
    session['proc'] = proc
    session['last_access'] = time.monotonic()
    return proc


def _log_tail(session, name, limit=800):
    try:
        text = (session['dir'] / name).read_text(
            encoding='utf-8', errors='replace')
    except OSError:
        return None
    return text[-limit:] if text else None


def _note_vaapi_failure(session):
    """Record why VAAPI failed and stop trying it for this process."""
    global _vaapi_broken, _last_vaapi_error
    error = _log_tail(session, 'ffmpeg-vaapi.log')
    session['vaapi_error'] = error
    session['vaapi_state'] = 'fallback'
    _last_vaapi_error = error
    _vaapi_broken = True


def _preserve_logs(session):
    """Copy a dying session's ffmpeg logs into <state>/transcode-logs."""
    try:
        logs = [p for p in session['dir'].glob('ffmpeg*.log') if p.is_file()]
        if not logs:
            return
        dest = Path(metadata.state_dir()) / 'transcode-logs'
        dest.mkdir(parents=True, exist_ok=True)
        stamp = time.strftime('%Y%m%d%H%M%S')
        for path in logs:
            shutil.copy2(path, dest / f"{session['id']}-{stamp}-{path.name}")
        kept = sorted(dest.glob('*.log'),
                      key=lambda p: p.stat().st_mtime)
        for old in kept[:-_LOG_KEEP]:
            try:
                old.unlink()
            except OSError:
                pass
    except OSError:
        pass


def _remove(session):
    _kill(session)
    _preserve_logs(session)
    shutil.rmtree(session['dir'], ignore_errors=True)


def _ensure_reaper():
    global _reaper_started
    if _reaper_started:
        return
    _reaper_started = True
    threading.Thread(target=_reaper_loop, daemon=True,
                     name='uav-transcode-reaper').start()


def _reaper_loop():
    while True:
        time.sleep(_REAPER_INTERVAL)
        now = time.monotonic()
        with _lock:
            doomed = [s for s in list(_sessions.values())
                      if now - s['last_access'] > _IDLE_LIMIT]
            for session in doomed:
                _sessions.pop(session['id'], None)
        for session in doomed:
            _remove(session)


def purge_all():
    """Kill every session and clear the transcode dir (server startup)."""
    with _lock:
        sessions = list(_sessions.values())
        _sessions.clear()
    for session in sessions:
        _remove(session)
    root = transcode_root()
    for child in root.iterdir():
        if child.is_dir():
            _preserve_logs({'id': child.name, 'dir': child})
            shutil.rmtree(child, ignore_errors=True)
        else:
            try:
                child.unlink()
            except OSError:
                pass


def _duration_for(rel, target):
    duration = float(probe.probe(rel).get('duration') or 0)
    if duration > 0:
        return duration
    data = probe._ffprobe_json(target)
    if data:
        try:
            return float((data.get('format') or {}).get('duration') or 0)
        except (TypeError, ValueError):
            pass
    return 0.0


def start(rel, offset=0.0):
    """Start a transcode session for *rel* near *offset* seconds.

    Returns the session dict.  Raises ValueError('not_found') when *rel*
    does not resolve, ValueError('no_duration') when the duration cannot
    be probed (the VOD playlist needs it), ValueError('busy') when
    MAX_SESSIONS are active.
    """
    target = library.resolve_stream(rel)
    if not target:
        raise ValueError('not_found')
    try:
        offset = max(0.0, float(offset))
    except (TypeError, ValueError):
        offset = 0.0
    duration = _duration_for(rel, target)
    if duration <= 0:
        raise ValueError('no_duration')
    _ensure_reaper()
    session_id = secrets.token_hex(8)
    session_dir = transcode_root() / session_id
    count = segment_count(duration)
    start_index = min(int(offset // SEG_LEN), count - 1)
    if Path(_VAAPI_DEVICE).exists():
        vaapi_state = 'fallback' if _vaapi_broken else 'active'
        vaapi_error = _last_vaapi_error if _vaapi_broken else None
    else:
        vaapi_state, vaapi_error = 'no_device', None
    with _lock:
        if len(_sessions) >= MAX_SESSIONS:
            raise ValueError('busy')
        session_dir.mkdir(parents=True, exist_ok=True)
        session = {'id': session_id, 'dir': session_dir, 'proc': None,
                   'rel': rel, 'target': target, 'offset': offset,
                   'duration': duration, 'nsegments': count,
                   'encoder': 'libx264', 'run_encoder': 'libx264',
                   'run_start_index': None,
                   'vaapi_state': vaapi_state, 'vaapi_error': vaapi_error,
                   'last_access': time.monotonic()}
        _sessions[session_id] = session
    try:
        with _lock:
            proc = _start_run(session, start_index)
        if session['run_encoder'] == 'vaapi':
            # Watchdog: a VAAPI ffmpeg that exits non-zero within ~2s
            # without producing a segment means the hardware path is
            # unusable; mark it broken and respawn in software.
            deadline = time.monotonic() + 2.0
            while time.monotonic() < deadline:
                if proc.poll() is not None:
                    break
                time.sleep(0.1)
            if (proc.poll() not in (None, 0)
                    and _frontier(session) < start_index):
                with _lock:
                    _note_vaapi_failure(session)
                    _start_run(session, start_index)
    except Exception:
        with _lock:
            _sessions.pop(session_id, None)
        _remove(session)
        raise
    return session


def ensure_segment(session, index):
    """Make seg<index>.ts available, (re)starting ffmpeg as policy decides.

    Policy: an existing file wins.  Otherwise, if the current run covers
    *index* and is within _FRONTIER_WAIT segments of it, wait for it;
    anything else (no run, finished run, *index* behind the run's start,
    far jump) restarts ffmpeg at *index* — earlier segments stay valid.
    A VAAPI run that dies aimed at *index* falls back to software once.
    Returns True when the file exists, False on transcode failure.
    """
    seg = session['dir'] / _seg_name(index)
    if seg.is_file():
        touch(session['id'])
        return True
    deadline = time.monotonic() + _SEG_WAIT
    fallback_used = False
    while time.monotonic() < deadline:
        if seg.is_file():
            touch(session['id'])
            return True
        with _lock:
            proc = session.get('proc')
            alive = proc is not None and proc.poll() is None
            if alive:
                # A run aimed exactly at *index* is producing it now —
                # always wait for it.  A run that started earlier only
                # counts if *index* is within _FRONTIER_WAIT of its
                # completed frontier; anything else restarts at *index*.
                run_start = session['run_start_index']
                wait = (run_start is not None and run_start <= index
                        and (run_start == index
                             or index - _frontier(session) <= _FRONTIER_WAIT))
                if not wait:
                    _start_run(session, index)
            elif proc is not None and session['run_start_index'] == index:
                # A run aimed exactly at this segment died without it.
                if (session['run_encoder'] == 'vaapi'
                        and not fallback_used):
                    _note_vaapi_failure(session)
                    fallback_used = True
                    _start_run(session, index)
                else:
                    return False
            else:
                _start_run(session, index)
        time.sleep(0.1)
    touch(session['id'])
    return seg.is_file()


def get(session_id):
    if not valid_id(session_id):
        return None
    with _lock:
        return _sessions.get(session_id)


def touch(session_id):
    with _lock:
        session = _sessions.get(session_id)
        if session is not None:
            session['last_access'] = time.monotonic()


def stop(session_id):
    """Kill and remove a session; unknown ids are ignored."""
    if not valid_id(session_id):
        return
    with _lock:
        session = _sessions.pop(session_id, None)
    if session is not None:
        _remove(session)
